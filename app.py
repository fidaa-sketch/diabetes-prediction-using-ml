import streamlit as st
import numpy as np
import joblib
from pathlib import Path

# Page configuration
st.set_page_config(
    page_title="Diabetes Prediction System",
    page_icon="🩺",
    layout="centered"
)

# Application heading
st.title("🩺 Diabetes Prediction System")
st.write(
    "A Machine Learning application for predicting "
    "diabetes using patient health information."
)

st.info(
    "Academic project demonstration only. "
    "This application does not provide a medical diagnosis."
)

# Load model and scaler
@st.cache_resource
def load_artifacts():
    folder = Path(__file__).parent
    model = joblib.load(folder / "diabetes_model.pkl")
    scaler = joblib.load(folder / "scaler.pkl")
    return model, scaler

try:
    model, scaler = load_artifacts()
    st.success("Machine learning model loaded successfully.")
except Exception as error:
    st.error("Could not load the model or scaler.")
    st.code(str(error))
    st.stop()

st.divider()
st.header("Enter Patient Details")

# Input form
with st.form("diabetes_form"):
    pregnancies = st.number_input(
        "Number of pregnancies",
        min_value=0, max_value=20, value=0
    )

    glucose = st.number_input(
        "Glucose level",
        min_value=0.0, max_value=300.0, value=120.0
    )

    blood_pressure = st.number_input(
        "Blood pressure",
        min_value=0.0, max_value=200.0, value=70.0
    )

    skin_thickness = st.number_input(
        "Skin thickness",
        min_value=0.0, max_value=100.0, value=20.0
    )

    insulin = st.number_input(
        "Insulin level",
        min_value=0.0, max_value=900.0, value=80.0
    )

    bmi = st.number_input(
        "BMI",
        min_value=0.0, max_value=80.0, value=25.0
    )

    pedigree = st.number_input(
        "Diabetes pedigree function",
        min_value=0.0, max_value=3.0, value=0.5
    )

    age = st.number_input(
        "Age",
        min_value=1, max_value=120, value=30
    )

    submitted = st.form_submit_button(
        "Predict",
        use_container_width=True
    )

# Prediction
if submitted:
    try:
        input_data = np.array([[
            pregnancies,
            glucose,
            blood_pressure,
            skin_thickness,
            insulin,
            bmi,
            pedigree,
            age
        ]], dtype=float)

        scaled_data = scaler.transform(input_data)
        prediction = int(model.predict(scaled_data)[0])

        st.divider()
        st.header("Prediction Result")

        if prediction == 1:
            st.error(
                "The model predicts the diabetes-positive class."
            )
        else:
            st.success(
                "The model predicts the diabetes-negative class."
            )

        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(scaled_data)[0]
            classes = list(model.classes_)

            if 1 in classes:
                probability = probabilities[classes.index(1)]
                st.metric(
                    "Model-estimated probability for class 1",
                    f"{probability * 100:.1f}%"
                )

        st.caption(
            "This result is generated by a machine-learning model. "
            "It is not a diagnosis or a substitute for professional "
            "medical advice."
        )

    except Exception as error:
        st.error("Prediction failed.")
        st.code(str(error))
        st.warning(
            "Check that your saved model and scaler match the "
            "training process and feature order."
        )

st.divider()
st.caption("Diabetes Prediction Using Machine Learning | Student Project")
